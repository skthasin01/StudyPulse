    /** Opens the login screen with the email already filled in (after sign-up or logout). */
    public LoginFrame(String email) {
        this();
        txtEmail.setText(email);
        txtPassword.requestFocusInWindow();
    }

    private void applyTheme() {
        UITheme.applyFrame(this);
        lblLogo.setText("");
        lblLogo.setIcon(UITheme.circleBadge("SP", 72, UITheme.ACCENT));
        UITheme.stylePrimaryButton(btnLogin);
        UITheme.styleLinkButton(btnCreateAccount);
        UITheme.styleLinkButton(btnLoadDemo);
        btnLoadDemo.setFont(UITheme.FONT_NORMAL);
        btnLoadDemo.setForeground(UITheme.TEXT_MUTED);
        UITheme.styleErrorLabel(lblError);
        chkShowPassword.setOpaque(false);
        txtEmail.putClientProperty("JTextField.placeholderText", "you@university.edu");
        passwordEchoChar = txtPassword.getEchoChar();
    }

    private void login() {
        UITheme.hideError(lblError);
        char[] password = txtPassword.getPassword();
        try {
            authService.login(txtEmail.getText(), password);
            applySavedTheme();
            DesktopAlerts.start();
            new DashboardFrame().setVisible(true);
            dispose();
        } catch (ServiceException ex) {
            UITheme.showError(lblError, ex.getMessage());
            txtPassword.setText("");
            txtPassword.requestFocusInWindow();
        } finally {
            Arrays.fill(password, '\0');
        }
    }

    /** Creates demo@studypulse.com / demo123 with three weeks of data and fills in the login fields. */
    private void loadDemoData() {
        setCursor(java.awt.Cursor.getPredefinedCursor(java.awt.Cursor.WAIT_CURSOR));
        try {
            boolean created = DemoDataSeeder.seed();
            txtEmail.setText(DemoDataSeeder.EMAIL);
            txtPassword.setText(DemoDataSeeder.PASSWORD);
            JOptionPane.showMessageDialog(this, (created ? "Demo data loaded: 12 tasks, 21 days of check-ins, "
                    + "study sessions, a study plan, risk history and notifications."
                    : "The demo account already exists.")
                    + "\n\nLog in with " + DemoDataSeeder.EMAIL + " / " + DemoDataSeeder.PASSWORD + ".",
                    "Demo data", JOptionPane.INFORMATION_MESSAGE);
        } catch (ServiceException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Demo data", JOptionPane.ERROR_MESSAGE);
        } finally {
            setCursor(java.awt.Cursor.getDefaultCursor());
        }
    }

    /** Light / dark from user_settings, before the dashboard opens. */
    private void applySavedTheme() {
        try {
            boolean dark = new SettingsService().getSettings().getTheme() == AppTheme.DARK;
            if (dark != UITheme.isDark()) {
                UITheme.switchTheme(dark);
            }
        } catch (ServiceException ex) {
            // keep the current theme
        }
    }

    private void togglePasswordVisible() {
        txtPassword.setEchoChar(chkShowPassword.isSelected() ? (char) 0 : passwordEchoChar);
    }

    private void openSignup() {
        new SignupFrame().setVisible(true);
        dispose();
    }

