    private void applyTheme() {
        UITheme.applyFrame(this);
        UITheme.stylePrimaryButton(btnSave);
    }

    private void setupTable() {
        tableModel = TableUtil.createModel(COL_HOURS, Double.class, "Day", "Free hours");
        tblAvailability.setModel(tableModel);
        UITheme.styleTable(tblAvailability);
        tblAvailability.getColumnModel().getColumn(COL_DAY).setPreferredWidth(130);
        tblAvailability.getColumnModel().getColumn(COL_HOURS).setCellEditor(new SpinnerCellEditor(0, 12, 0.5));
        tblAvailability.putClientProperty("terminateEditOnFocusLost", Boolean.TRUE);
        tblAvailability.setSurrendersFocusOnKeystroke(true);
    }

    private void loadData() {
        try {
            rows = availabilityService.getAvailability();
        } catch (ServiceException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "StudyPulse", JOptionPane.ERROR_MESSAGE);
            return;
        }
        tableModel.setRowCount(0);
        for (Availability a : rows) {
            tableModel.addRow(new Object[]{a.getId(), DateUtil.dayName(a.getDayOfWeek()), a.getFreeMinutes() / 60.0});
        }
        cmbRestDay.setSelectedIndex(availabilityService.getRestDay() - 1);
        updateRestDayLabels();
    }

    /** Marks the rest day row in the Day column. */
    private void updateRestDayLabels() {
        int restDay = cmbRestDay.getSelectedIndex() + 1;
        for (int i = 0; i < rows.size(); i++) {
            int day = rows.get(i).getDayOfWeek();
            tableModel.setValueAt(DateUtil.dayName(day) + (day == restDay ? " (rest day)" : ""), i, COL_DAY);
        }
    }

    private void save() {
        if (tblAvailability.isEditing()) {
            tblAvailability.getCellEditor().stopCellEditing();
        }
        for (int i = 0; i < rows.size(); i++) {
            double hours = ((Number) tableModel.getValueAt(i, COL_HOURS)).doubleValue();
            rows.get(i).setFreeMinutes((int) Math.round(hours * 2) * 30);
        }
        try {
            availabilityService.save(rows, cmbRestDay.getSelectedIndex() + 1);
            JOptionPane.showMessageDialog(this, "Your free time is saved.\nGenerate the plan again to use it.",
                    "StudyPulse", JOptionPane.INFORMATION_MESSAGE);
            if (onSaved != null) {
                onSaved.run();
            }
            dispose();
        } catch (ServiceException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "StudyPulse", JOptionPane.WARNING_MESSAGE);
        }
    }

