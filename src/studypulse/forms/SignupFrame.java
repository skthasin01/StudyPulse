    private void applyTheme() {
        UITheme.applyFrame(this);
        UITheme.stylePrimaryButton(btnSignup);
        UITheme.styleLinkButton(btnBackToLogin);
        UITheme.styleErrorLabel(lblError);
        chkWellbeing.setOpaque(false);
        txtFullName.putClientProperty("JTextField.placeholderText", "e.g. Ayesha Rahman");
        txtEmail.putClientProperty("JTextField.placeholderText", "you@university.edu");
    }

    private void signup() {
        UITheme.hideError(lblError);
        char[] password = txtPassword.getPassword();
        char[] confirm = txtConfirmPassword.getPassword();
        try {
            User user = authService.register(txtFullName.getText(), txtEmail.getText(),
                    password, confirm, chkWellbeing.isSelected());
            JOptionPane.showMessageDialog(this,
                    "Account created. Welcome to StudyPulse, " + user.getFullName() + "!",
                    "StudyPulse", JOptionPane.INFORMATION_MESSAGE);
            DesktopAlerts.start();
            new DashboardFrame().setVisible(true);
            dispose();
        } catch (ServiceException ex) {
            UITheme.showError(lblError, ex.getMessage());
        } finally {
            Arrays.fill(password, '\0');
            Arrays.fill(confirm, '\0');
        }
    }

    private void backToLogin() {
        new LoginFrame().setVisible(true);
        dispose();
    }

